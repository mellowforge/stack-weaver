#!/usr/bin/env node
// Writes src/version.ts from package.json's `version`, so `VERSION` can never drift from the
// published version. The output is gitignored; pretest, prebuild and pretypecheck run this first.
//
//   node scripts/gen-version.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
if (typeof version !== 'string' || version === '') throw new Error('package.json has no version');

const out = join(root, 'src', 'version.ts');
const text = `// Generated by scripts/gen-version.mjs from package.json. Do not edit.

/** The version of \`@mellowforge/stack-weaver-core\`, taken from its package.json. */
export const VERSION = ${JSON.stringify(version)};
`;
if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
  writeFileSync(out, text);
  console.log(`wrote src/version.ts (${version})`);
}
